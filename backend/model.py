import requests
import pandas as pd

TOKEN = "90f438a4e0cfd96752edd5cc8db6d2440f91e45f"

user_location = input("Enter the city or location to predict AQI: ")

search_url = f"https://api.waqi.info/search/?token={TOKEN}&keyword={user_location}"
search_response = requests.get(search_url).json()

found_stations = []
if search_response['status'] == 'ok' and search_response['data']:
    for s_info in search_response['data']:
        found_stations.append({
            'name': s_info['station']['name'],
            'uid': s_info['uid']
        })
else:
    print(f"Error or no stations found for '{user_location}':", search_response)

predicted_aqi_results_by_location = {}
predicted_values = [] # Initialize list to store all predicted AQI values
actual_values = []    # Initialize list to store all actual AQI values

if not found_stations:
    print(f"No stations found for '{user_location}'. Cannot predict AQI.")
else:
    print(f"Predicting AQI for stations in '{user_location}'...")
    for station_item in found_stations:
        station_name = station_item['name']
        station_uid = station_item['uid']

        feed_url = f"https://api.waqi.info/feed/@{station_uid}/?token={TOKEN}"
        feed_response = requests.get(feed_url).json()

        if feed_response['status'] == 'ok' and 'data' in feed_response:
            iaqi_data = feed_response['data'].get('iaqi', {})
            actual_aqi = feed_response['data'].get('aqi')  # <-- Actual AQI from WAQI

            pm25 = iaqi_data.get('pm25', {}).get('v')
            pm10 = iaqi_data.get('pm10', {}).get('v')
            so2 = iaqi_data.get('so2', {}).get('v')
            no2 = iaqi_data.get('no2', {}).get('v')
            co = iaqi_data.get('co', {}).get('v')
            o3 = iaqi_data.get('o3', {}).get('v')


            if all(v is not None for v in [pm25, pm10, so2, no2, co,o3]):
                api_input_df = pd.DataFrame([[
                    pm25,
                    pm10,
                    so2,
                    no2,
                    co,
                    o3
                ]], columns=['PM2.5', 'PM10', 'SO2', 'NO2', 'CO','O3'])

                predicted_aqi = model.predict(api_input_df)[0]
                predicted_values.append(predicted_aqi) # Append predicted AQI
                if actual_aqi is not None: # Only append if actual_aqi is available
                    actual_values.append(actual_aqi) # Append actual AQI

                predicted_aqi_results_by_location[station_name] = {
                    "predicted": f"{predicted_aqi:.2f}",
                    "actual": actual_aqi
                }
            else:
                predicted_aqi_results_by_location[station_name] = {
                    "predicted": "Missing pollutant data for prediction",
                    "actual": actual_aqi
                }
        else:
            predicted_aqi_results_by_location[station_name] = {
                "predicted": "Error fetching detailed data",
                "actual": None
            }

def get_category(aqi):
    if aqi <= 50:
        return "Good"
    elif aqi <= 100:
        return "Moderate"
    elif aqi <= 200:
        return "Unhealthy"
    else:
        return "Hazardous"

print(f"\n--- AQI Predictions for '{user_location}' Stations ---")
if predicted_aqi_results_by_location:
    for station, results in predicted_aqi_results_by_location.items():
        predicted = results["predicted"]
        actual = results["actual"]

        if isinstance(predicted, str) and not predicted.replace('.', '', 1).isdigit():
            print(f"  {station}: Predicted={predicted}, Actual={actual}")
        else:
            print(f"  {station}: Predicted={predicted} ({get_category(float(predicted))}), Actual={actual} ({get_category(actual) if actual is not None else 'N/A'})")
else:
    print(f"No predictions could be made for '{user_location}'.")

